const messages: Record<Locale, Record<WebKey, string>> = { en, ar };

export function t(locale: Locale, key: WebKey, vars?: Record<string, string | number>): string {
  const raw = messages[locale][key] ?? en[key];
  return vars ? raw.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : raw;
}

/** Texts the booking script needs in the browser. */
export function clientMessages(locale: Locale): Record<string, string> {
  return Object.fromEntries(
    Object.entries(messages[locale]).filter(([k]) => /^(book|request|booking|doctors\.minutes|currency)\./.test(k) || k === "doctors.minutes"),
  );
}

export const pick = (locale: Locale, ar: string | null | undefined, en: string | null | undefined): string =>
  (locale === "ar" ? ar || en : en || ar) ?? "";

export function formatPrice(locale: Locale, amount: number, currency = "SYP"): string {
  const n = new Intl.NumberFormat(locale === "ar" ? "ar-SY-u-nu-latn" : "en-GB").format(amount);
  const unit = currency === "SYP" ? t(locale, "currency.SYP") : currency;
  return `${n} ${unit}`;
}

/** "{n} doctors" with correct plural forms (Arabic has six). */
export function doctorCount(locale: Locale, n: number): string {
  const fmt = new Intl.NumberFormat(locale === "ar" ? "ar-SY-u-nu-latn" : "en-GB").format(n);
  if (locale === "en") return n === 1 ? "1 doctor" : `${fmt} doctors`;
  const rule = new Intl.PluralRules("ar").select(n);
  return { zero: "لا يوجد أطباء", one: "طبيب واحد", two: "طبيبان", few: `${fmt} أطباء`, many: `${fmt} طبيباً`, other: `${fmt} طبيب` }[rule];
}
